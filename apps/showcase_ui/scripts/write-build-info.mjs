// Bundles the build commit into the page so the footer can name the build the
// browser runs (CHE-1411). ARTEMIS_BUILD_SHA wins (Docker and preview builds
// have no .git); otherwise git HEAD; otherwise "unknown".
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SHA = /^[0-9a-f]{7,40}$/i;

export function resolveBuildSha(env = process.env, cwd = process.cwd()) {
  if (SHA.test(env.ARTEMIS_BUILD_SHA || '')) return env.ARTEMIS_BUILD_SHA.toLowerCase();
  try {
    const head = execFileSync('git', ['rev-parse', 'HEAD'], { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
    if (SHA.test(head)) return head.toLowerCase();
  } catch {
    // No git binary or not a checkout.
  }
  return 'unknown';
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const info = { sha: resolveBuildSha(), builtAt: new Date().toISOString() };
  writeFileSync(
    new URL('../src/build-info.ts', import.meta.url),
    `// Generated by scripts/write-build-info.mjs; do not edit.\nexport const BUILD_INFO = ${JSON.stringify(info)};\n`
  );
}
